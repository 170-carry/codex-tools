import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const modulePath = process.env.CODEX_TOOLS_PLAYWRIGHT_MODULE;
const { chromium } = await import(modulePath ? pathToFileURL(modulePath).href : 'playwright');
const browser = await chromium.launch({channel:'chrome',headless:true});
const errors=[];const checks=[];
const base='http://127.0.0.1:5199/tests/ui/preview.html?auto=on';
async function open(extra='') {
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{if(window===top)localStorage.setItem('codex-tools-layout','compact')});
  await page.clock.install();
  await page.goto(base+extra);
  await page.getByRole('heading',{name:'代码统计',exact:true}).waitFor();
  return page;
}
const count=page=>page.evaluate(()=>window.__previewCommands.filter(command=>command==='run_git_activity').length);
async function completed(page, expected) {
  await page.waitForFunction(expected=>window.__previewCommands.filter(command=>command==='run_git_activity').length===expected,expected);
  await page.getByRole('button',{name:'生成 / 更新日历',exact:true}).waitFor();
}
try {
  const page=await open();
  await completed(page,1);
  const frame=page.frameLocator('.gitActivityCalendar');
  await frame.locator('#year').selectOption('2025');
  await frame.locator('#repo').selectOption('demo');
  await frame.locator('#who').selectOption('bob@example.com');
  await frame.locator('.more>summary').click();
  await frame.locator('#heat').selectOption('lines');
  await frame.locator('#bulk').check();
  await frame.locator('.more>summary').click();
  await page.clock.fastForward(15*60_000+1000);
  await completed(page,2);
  await frame.locator('.cardmonth').getByText('2025 年 12 月',{exact:true}).waitFor();
  assert.equal(await frame.locator('#who').inputValue(),'bob@example.com');
  assert.equal(await frame.locator('#repo').inputValue(),'demo');
  assert.equal(await frame.locator('#heat').inputValue(),'lines');
  assert(await frame.locator('#bulk').isChecked());
  checks.push('startup + 15-minute refresh preserve month, person, repo, heat and bulk filters');
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  await page.getByLabel('手动排除姓名或邮箱').fill('not-in-repo@example.com');
  await page.getByRole('button',{name:'加入排除',exact:true}).click();
  await page.clock.fastForward(16*60_000);
  assert.equal(await count(page),2,'paused while editing');
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  await page.clock.fastForward(60_000);
  assert.equal(await count(page),2,'closed settings do not auto-apply unsaved edits');
  await page.getByRole('button',{name:'生成 / 更新日历',exact:true}).click();
  await completed(page,3);
  await page.clock.fastForward(15*60_000+1000);
  await completed(page,4);
  await page.getByRole('tab',{name:/^账号/}).click();
  await page.clock.fastForward(15*60_000+1000);
  await page.waitForFunction(()=>window.__previewCommands.filter(command=>command==='run_git_activity').length===5);
  await page.getByRole('tab',{name:/代码统计/}).click();
  await completed(page,5);
  checks.push('editing and unapplied drafts pause refresh; it resumes after applying and works on other tabs');
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  await page.getByLabel('打开程序时自动更新').uncheck();
  await page.getByLabel('自动更新间隔').selectOption('0');
  await page.screenshot({path:'.codex-verification/git-activity/auto-settings.png'});
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  await page.clock.fastForward(60*60_000);
  assert.equal(await count(page),5,'disabled timer does not run');
  await page.reload();
  await page.locator('.gitActivityCalendar').waitFor();
  await page.clock.fastForward(60*60_000);
  assert.equal(await count(page),0,'disabled preferences persist after restart');
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  assert.equal(await page.getByLabel('自动更新间隔').inputValue(),'0');
  assert.equal(await page.getByLabel('打开程序时自动更新').isChecked(),false);
  await page.getByLabel('自动更新间隔').selectOption('5');
  await page.getByRole('button',{name:'仓库设置',exact:true}).click();
  await page.clock.fastForward(5*60_000+1000);
  await completed(page,1);
  checks.push('turn off persists across reload; selecting five minutes enables the new interval');
  await page.close();

  const held=await open('&hold=yes');
  await held.waitForFunction(()=>!!window.__releaseGitRun);
  await held.clock.fastForward(60*60_000);
  assert.equal(await count(held),1,'long-running task never overlaps');
  await held.evaluate(()=>window.__releaseGitRun());
  await completed(held,1);
  await held.clock.fastForward(15*60_000+1000);
  await held.waitForFunction(()=>window.__previewCommands.filter(command=>command==='run_git_activity').length===2);
  await held.evaluate(()=>window.__releaseGitRun());
  await completed(held,2);
  await held.close();
  checks.push('one update at a time and no burst after a long operation');

  const failure=await open('&git=failure');
  await completed(failure,1);
  assert(await failure.locator('.gitActivityCalendar').isVisible());
  await failure.clock.fastForward(60_000);
  assert.equal(await count(failure),1,'failure is not immediately retried');
  await failure.clock.fastForward(15*60_000);
  await completed(failure,2);
  assert(await failure.locator('.gitActivityCalendar').isVisible());
  await failure.close();
  const empty=await open('&git=unconfigured');
  await empty.clock.fastForward(60*60_000);
  assert.equal(await count(empty),0,'no repository means no background collection');
  await empty.close();
  checks.push('failure keeps prior calendar and retries next interval; empty setup does not run');
  assert.deepEqual(errors,[]);
  await mkdir('.codex-verification/git-activity',{recursive:true});
  await writeFile('.codex-verification/git-activity/auto-checks.json',JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
} finally {await browser.close()}
