import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const modulePath = process.env.CODEX_TOOLS_PLAYWRIGHT_MODULE;
const { chromium } = await import(modulePath ? pathToFileURL(modulePath).href : 'playwright');
const browser = await chromium.launch({channel:'chrome',headless:true});
const errors=[];const checks=[];
await mkdir('.codex-verification/git-activity',{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(()=>{if(window===top)localStorage.setItem('codex-tools-layout','compact')});
  await page.clock.install();
  await page.goto('http://127.0.0.1:5199/tests/ui/preview.html?auto=on&git=layout');
  await page.waitForFunction(()=>window.__previewCommands.includes('run_git_activity'));
  await page.getByRole('button',{name:'生成 / 更新日历',exact:true}).waitFor();
  const frame=page.frameLocator('.gitActivityCalendar');
  await frame.locator('.person').nth(3).waitFor();
  const columns=async()=>frame.locator('#grid').evaluate(grid=>getComputedStyle(grid).gridTemplateColumns.split(' ').length);
  await frame.getByLabel('日历布局').selectOption('1');
  assert.equal(await columns(),1);
  await frame.getByLabel('日历布局').selectOption('2');
  assert.equal(await columns(),2);
  await frame.getByLabel('日历布局').selectOption('3');
  assert.equal(await columns(),3);
  const positions=await frame.locator('.person').evaluateAll(cards=>cards.map(card=>card.getBoundingClientRect().top));
  assert.equal(positions[0],positions[2]);assert(positions[3]>positions[0]);
  const tall=(await frame.locator('.day').first().boundingBox()).height;
  await frame.getByLabel('紧凑显示').check();
  assert((await frame.locator('.day').first().boundingBox()).height<tall,'compact reduces day height');
  assert.equal(await frame.locator('.person').count(),4,'all people remain visible');
  assert.equal(await frame.locator('.person').first().locator('[data-day="2026-10-08"] .invalid-flag').count(),1);
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('codex-tools-git-calendar-layout')||'{}').density==='compact');
  await page.screenshot({path:'.codex-verification/git-activity/layout-three.png'});
  await page.clock.fastForward(15*60_000+1000);
  await page.waitForFunction(()=>window.__previewCommands.filter(command=>command==='run_git_activity').length===2);
  await page.getByRole('button',{name:'生成 / 更新日历',exact:true}).waitFor();
  await frame.locator('body[data-columns="3"][data-density="compact"]').waitFor();
  checks.push('one/two/three columns, compact density, all data retained, automatic refresh preserves layout');
  await page.reload();
  await frame.locator('body[data-columns="3"][data-density="compact"]').waitFor();
  await page.getByRole('button',{name:'生成 / 更新日历',exact:true}).waitFor();
  assert.equal(await frame.getByLabel('日历布局').inputValue(),'3');
  await page.setViewportSize({width:1300,height:1000});
  assert.equal(await columns(),2,'three-column preference adapts to medium width');
  await page.setViewportSize({width:760,height:950});
  assert.equal(await columns(),1,'small windows use one readable column');
  assert(await frame.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'.codex-verification/git-activity/layout-narrow.png'});
  await page.setViewportSize({width:1920,height:1080});
  assert.equal(await columns(),3,'chosen column count restored after resizing');
  await page.getByRole('button',{name:'保存独立 HTML',exact:true}).click();
  const html=await page.evaluate(()=>window.__gitActivityExport);
  const standalone=await browser.newPage({viewport:{width:1920,height:1080}});
  standalone.on('pageerror',error=>errors.push(error.message));
  await standalone.setContent(html);
  await standalone.locator('body[data-columns="3"][data-density="compact"]').waitFor();
  await standalone.getByLabel('日历布局').selectOption('1');
  assert.equal(await standalone.locator('#grid').evaluate(grid=>getComputedStyle(grid).gridTemplateColumns.split(' ').length),1);
  checks.push('preferences survive restart, responsive fallback avoids overflow, export retains layout and controls');
  assert.deepEqual(errors,[]);
  await writeFile('.codex-verification/git-activity/layout-checks.json',JSON.stringify({checks,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
} finally {await browser.close()}
